import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const root = dirname(fileURLToPath(import.meta.url));
// Concatenate local modules and resolve shared UI dependencies through the DSH loader.
const files = ['domain.js', 'queue.js', 'rpc.js', 'style.js', 'client-entry.js'];
let body = '';
for (const file of files) {
  let source = await readFile(resolve(root, file), 'utf8');
  source = source.replace(/^import .+ from ['"].+['"];\r?\n/gmu, '').replace(/^export /gmu, '');
  body += `\n// ${file}\n${source}`;
}
const en = JSON.parse(await readFile(resolve(root, 'locale/en.json'), 'utf8'));
const zh = JSON.parse(await readFile(resolve(root, 'locale/zh.json'), 'utf8'));
const output = `// Generated by build.mjs. Edit the listed source modules, then rebuild.\nwindow.__ModuleLoader__.load({\n  id: '@local/dsh-resource-picker',\n  factory(require) {\n    const React = require('react');\n    const { z } = require('zod');\n    const { Modal } = require('@deepseek-ai/dsh-client-ui-primitives');\n    const en = ${JSON.stringify(en)};\n    const zh = ${JSON.stringify(zh)};\n${body}\n    return { inject, apply };\n  }\n});\n`;
if (process.argv.includes('--check')) {
  const current = await readFile(resolve(root, 'client.js'), 'utf8');
  if (current !== output) throw new Error('client.js is stale; run node build.mjs');
} else await writeFile(resolve(root, 'client.js'), output);
